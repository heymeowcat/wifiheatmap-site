/**
 * Downloads the `latin` subset of the self-hosted webfonts used by the site.
 * Run with: node scripts/fetch-fonts.mjs
 *
 * Self-hosting removes the render-blocking Google Fonts stylesheet request,
 * which is one of the largest Core Web Vitals (LCP/TTFB) wins available.
 *
 * Both families ship as variable fonts from Google Fonts, so every requested
 * weight resolves to the *same* binary. We de-duplicate by content hash and
 * emit a single `@font-face` per family with a `font-weight` range, which
 * takes the payload from ~290 kB down to ~64 kB.
 */
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const UA =
	"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const FAMILIES = [
	{
		family: "Outfit",
		slug: "outfit-var",
		weightRange: "100 900",
		url: "https://fonts.googleapis.com/css2?family=Outfit:wght@300;400;500;600;700;800;900&display=swap",
	},
	{
		family: "JetBrains Mono",
		slug: "jetbrains-mono-var",
		weightRange: "100 800",
		url: "https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;600&display=swap",
	},
];

const OUT_DIR = path.resolve("public/fonts");

/** Latin subset detection: contains U+0000-00FF. */
const isLatin = (range) => range.includes("U+0000-00FF");

function parseFaces(css) {
	const faces = [];
	for (const block of css.split("@font-face").slice(1)) {
		const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
		const weight = /font-weight:\s*(\d+)/.exec(block)?.[1];
		const src = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
		const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1] ?? "";
		if (!family || !weight || !src) continue;
		faces.push({ family, weight, src, range });
	}
	return faces;
}

async function main() {
	await mkdir(OUT_DIR, { recursive: true });

	const cssBlocks = [];

	for (const meta of FAMILIES) {
		const css = await fetch(meta.url, { headers: { "User-Agent": UA } }).then((r) => r.text());
		const latin = parseFaces(css).filter((f) => isLatin(f.range));

		const byHash = new Map();
		for (const face of latin) {
			const bytes = Buffer.from(
				await fetch(face.src, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer()),
			);
			const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 8);
			if (!byHash.has(hash)) byHash.set(hash, bytes);
		}

		// One file per unique binary (variable fonts => exactly one).
		let index = 0;
		for (const bytes of byHash.values()) {
			const name = byHash.size === 1 ? `${meta.slug}.woff2` : `${meta.slug}-${index}.woff2`;
			await writeFile(path.join(OUT_DIR, name), bytes);
			console.log(`↓ ${name} (${(bytes.length / 1024).toFixed(1)} kB)`);
			index += 1;
		}

		cssBlocks.push(`@font-face {
  font-family: '${meta.family}';
  font-style: normal;
  font-weight: ${meta.weightRange};
  font-display: swap;
  src: url('/fonts/${meta.slug}.woff2') format('woff2');
  unicode-range: ${latin[0]?.range ?? "U+0000-00FF"};
}`);
	}

	const localCss = `/* Self-hosted webfonts — generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n${cssBlocks.join("\n\n")}\n`;
	await writeFile(path.join(OUT_DIR, "fonts.css"), localCss, "utf8");
	console.log("\n✓ fonts.css written to public/fonts/");
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
